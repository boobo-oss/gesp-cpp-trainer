function gespGraph(n, extra) {
  var edges = [];
  for (var i = 1; i < n; i++) edges.push([i, i + 1, G.ri(1, 9)]);
  for (var k = 0; k < extra; k++) {
    var u = G.ri(1, n), v = G.ri(1, n);
    if (u === v) { k--; continue; }
    edges.push([u, v, G.ri(1, 9)]);
  }
  return edges;
}

