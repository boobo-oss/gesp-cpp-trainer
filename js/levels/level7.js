function gespMinPath(g) {
  var n = g.length, m = g[0].length, dp = [];
  for (var i = 0; i < n; i++) dp.push(new Array(m).fill(0));
  for (i = 0; i < n; i++)
    for (var j = 0; j < m; j++) {
      var best = i === 0 && j === 0 ? 0 : Infinity;
      if (i > 0) best = Math.min(best, dp[i - 1][j]);
      if (j > 0) best = Math.min(best, dp[i][j - 1]);
      dp[i][j] = best + g[i][j];
    }
  return dp[n - 1][m - 1];
}

